-- Google Sheets module: people sync tables the administrator allows into their own Google spreadsheets.

-- Google accounts connected for Sheets (several per person; separate from the Gmail/Calendar connection). Tokens encrypted.
CREATE TABLE IF NOT EXISTS gsheet_accounts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    google_email   VARCHAR(190) NOT NULL,
    access_token   TEXT,
    refresh_token  TEXT,
    expires_at     TIMESTAMPTZ,
    last_error     VARCHAR(255),
    connected_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, google_email)
);

-- Tables the administrator has opened for syncing (db = connection key: core, crm, accounting …).
CREATE TABLE IF NOT EXISTS gsheet_tables (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    db             VARCHAR(40)  NOT NULL,
    table_name     VARCHAR(120) NOT NULL,
    label          VARCHAR(120),
    enabled        BOOLEAN      NOT NULL DEFAULT FALSE,
    hidden_columns TEXT         NOT NULL DEFAULT '[]',     -- JSON list of columns never sent
    updated_by     BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (db, table_name)
);

-- Who may sync a table: a whole role or one person.
CREATE TABLE IF NOT EXISTS gsheet_table_access (
    table_id  BIGINT NOT NULL REFERENCES gsheet_tables(id) ON DELETE CASCADE,
    role_id   BIGINT REFERENCES roles(id) ON DELETE CASCADE,
    user_id   BIGINT REFERENCES users(id) ON DELETE CASCADE,
    CHECK ((role_id IS NULL) <> (user_id IS NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS gsheet_table_access_role ON gsheet_table_access (table_id, role_id) WHERE role_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS gsheet_table_access_user ON gsheet_table_access (table_id, user_id) WHERE user_id IS NOT NULL;

-- One table → one tab of one spreadsheet, on a schedule. A table can go to many sheets.
CREATE TABLE IF NOT EXISTS gsheet_syncs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    table_id         BIGINT NOT NULL REFERENCES gsheet_tables(id) ON DELETE CASCADE,
    account_id       BIGINT NOT NULL REFERENCES gsheet_accounts(id) ON DELETE CASCADE,
    spreadsheet_id   VARCHAR(128) NOT NULL,
    spreadsheet_name VARCHAR(255),
    sheet_tab        VARCHAR(100) NOT NULL,
    mode             VARCHAR(10)  NOT NULL CHECK (mode IN ('daily', 'once')),
    days             VARCHAR(20)  NOT NULL DEFAULT '1,2,3,4,5',   -- ISO weekdays (1 = Monday) for 'daily'
    run_time         TIME         NOT NULL,
    run_date         DATE,                                          -- for 'once'
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    next_run_at      TIMESTAMPTZ,
    running_since    TIMESTAMPTZ,
    last_run_at      TIMESTAMPTZ,
    last_status      VARCHAR(10),                                   -- ok | error
    last_message     VARCHAR(500),
    last_rows        INTEGER,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS gsheet_syncs_due ON gsheet_syncs (next_run_at) WHERE active;
CREATE INDEX IF NOT EXISTS gsheet_syncs_user ON gsheet_syncs (user_id);
