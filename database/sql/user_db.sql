-- =====================================================================
--  user_db  —  CORE: people, roles, permissions, work, security, logs
-- =====================================================================

CREATE TABLE IF NOT EXISTS settings (
    key         VARCHAR(100) PRIMARY KEY,
    value       TEXT,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80)  NOT NULL,
    slug        VARCHAR(40)  NOT NULL UNIQUE,
    description VARCHAR(255),
    level       SMALLINT     NOT NULL DEFAULT 10,          -- higher = more senior
    data_scope  VARCHAR(20)  NOT NULL DEFAULT 'own'
                CHECK (data_scope IN ('all','department','team','own')),
    is_system   BOOLEAN      NOT NULL DEFAULT FALSE,       -- built-in roles cannot be deleted
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- One row per thing you can grant access to ("members", later "crm.customers")
CREATE TABLE IF NOT EXISTS permissions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module      VARCHAR(40)  NOT NULL DEFAULT 'core',
    key         VARCHAR(80)  NOT NULL UNIQUE,
    label       VARCHAR(120) NOT NULL,
    sort        SMALLINT     NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS role_permissions (
    role_id       BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
    can_view      BOOLEAN NOT NULL DEFAULT FALSE,
    can_create    BOOLEAN NOT NULL DEFAULT FALSE,
    can_edit      BOOLEAN NOT NULL DEFAULT FALSE,
    can_delete    BOOLEAN NOT NULL DEFAULT FALSE,
    can_import    BOOLEAN NOT NULL DEFAULT FALSE,
    can_export    BOOLEAN NOT NULL DEFAULT FALSE,
    can_download  BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE IF NOT EXISTS departments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    code        VARCHAR(20)  NOT NULL UNIQUE,
    description TEXT,
    head_id     BIGINT,                                   -- BU manager (FK below)
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at  TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS teams (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE CASCADE,
    name          VARCHAR(120) NOT NULL,
    description   TEXT,
    lead_id       BIGINT,                                 -- manager (FK below)
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at    TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120) NOT NULL,
    email           VARCHAR(190) NOT NULL,
    password        VARCHAR(255) NOT NULL,
    role_id         BIGINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    department_id   BIGINT REFERENCES departments(id) ON DELETE SET NULL,
    team_id         BIGINT REFERENCES teams(id) ON DELETE SET NULL,
    manager_id      BIGINT REFERENCES users(id) ON DELETE SET NULL,
    data_scope      VARCHAR(20) CHECK (data_scope IN ('all','department','team','own')),  -- NULL = use role scope
    avatar          VARCHAR(255),
    is_active       BOOLEAN     NOT NULL DEFAULT TRUE,
    session_version INTEGER     NOT NULL DEFAULT 1,       -- bump to sign out every device
    last_login_at   TIMESTAMPTZ,
    last_login_ip   VARCHAR(45),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique ON users (lower(email));
CREATE INDEX IF NOT EXISTS users_department_idx ON users (department_id);
CREATE INDEX IF NOT EXISTS users_team_idx ON users (team_id);

