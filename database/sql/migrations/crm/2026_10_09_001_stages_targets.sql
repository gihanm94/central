-- Opportunity stage colours and which stages each department may use, yearly sales targets, reminder tracking.

-- The stage list itself is fixed (it matches the OpportunityStage enum); only the colour is a setting.
CREATE TABLE IF NOT EXISTS crm_stages (
    code  VARCHAR(30) PRIMARY KEY,
    color VARCHAR(9) NOT NULL,
    sort  SMALLINT NOT NULL
);
INSERT INTO crm_stages (code, color, sort) VALUES
