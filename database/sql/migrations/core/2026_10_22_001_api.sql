-- Mobile / API access. Only people whose role (or own permissions) hold "Mobile app & API" may sign in through the API.
INSERT INTO permissions (module, key, label, sort)
SELECT 'core', 'api_access', 'Mobile app & API', 90
WHERE EXISTS (SELECT 1 FROM roles)
ON CONFLICT (key) DO NOTHING;

-- One row per signed-in device. Tokens are never stored, only their SHA-256.
-- The access token lives minutes; the refresh token rotates on every use (a reused old one ends the device's sign-in).
CREATE TABLE IF NOT EXISTS api_devices (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name                VARCHAR(120) NOT NULL,                 -- "Somchai's iPhone" (sent by the app)
    device_key          VARCHAR(120),                          -- the app's own install id
    platform            VARCHAR(40),
    access_hash         CHAR(64),
    access_expires_at   TIMESTAMPTZ,
    refresh_hash        CHAR(64),
    prev_refresh_hash   CHAR(64),                              -- the refresh token just replaced: seeing it again = stolen
    refresh_expires_at  TIMESTAMPTZ,
    session_version     INTEGER      NOT NULL,                 -- users.session_version at sign-in ("sign out everywhere" ends API sign-ins too)
    expires_at          TIMESTAMPTZ  NOT NULL,                 -- hard end of this sign-in
    created_ip          VARCHAR(45),
    last_ip             VARCHAR(45),
    last_used_at        TIMESTAMPTZ,
    user_agent          VARCHAR(255),
    revoked_at          TIMESTAMPTZ,
    revoked_reason      VARCHAR(40),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS api_devices_access ON api_devices (access_hash) WHERE access_hash IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS api_devices_refresh ON api_devices (refresh_hash) WHERE refresh_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS api_devices_prev_refresh ON api_devices (prev_refresh_hash) WHERE prev_refresh_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS api_devices_user ON api_devices (user_id);

-- Fixed-window request counters (per device, per IP for sign-in).
CREATE TABLE IF NOT EXISTS api_rate (
    key          VARCHAR(120) NOT NULL,
    window_start TIMESTAMPTZ  NOT NULL,
    hits         INTEGER      NOT NULL DEFAULT 0,
    PRIMARY KEY (key, window_start)
);

-- Every API request (kept 90 days): who, what, result.
CREATE TABLE IF NOT EXISTS api_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    request_id  CHAR(16)     NOT NULL,
    device_id   BIGINT,
    user_id     BIGINT,
    method      VARCHAR(8)   NOT NULL,
    path        VARCHAR(255) NOT NULL,
    status      SMALLINT     NOT NULL,
    ms          INTEGER      NOT NULL,
    ip          VARCHAR(45),
    error       VARCHAR(60)
);
CREATE INDEX IF NOT EXISTS api_log_at ON api_log (at);
CREATE INDEX IF NOT EXISTS api_log_user ON api_log (user_id, at);
