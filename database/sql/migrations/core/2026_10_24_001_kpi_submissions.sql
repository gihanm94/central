-- KPI / OKR submissions (User Management → KPI submissions).
-- A task can be a KPI or an OKR with a criteria (1–100); each month people submit their result for it once.
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS kind     VARCHAR(10) NOT NULL DEFAULT 'task';
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS criteria NUMERIC(6,2);
DO $$ BEGIN
    ALTER TABLE tasks ADD CONSTRAINT tasks_kind_check CHECK (kind IN ('task','kpi','okr'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
CREATE INDEX IF NOT EXISTS tasks_kind_assignee_idx ON tasks (kind, assigned_to) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS kpi_submissions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,       -- who submitted (always the signed-in person)
    department_id BIGINT REFERENCES departments(id) ON DELETE SET NULL,          -- copied from the person when submitting
    team_id       BIGINT REFERENCES teams(id) ON DELETE SET NULL,
    task_id       BIGINT REFERENCES tasks(id) ON DELETE SET NULL,
    task_title    VARCHAR(200) NOT NULL,                                          -- kept as submitted, even if the task is renamed later
    task_kind     VARCHAR(10)  NOT NULL,
    criteria      NUMERIC(6,2),
    period_year   SMALLINT NOT NULL CHECK (period_year BETWEEN 2000 AND 2100),
    period_month  SMALLINT NOT NULL CHECK (period_month BETWEEN 1 AND 12),
    approver_id   BIGINT REFERENCES users(id) ON DELETE SET NULL,
    finished      NUMERIC(14,2) NOT NULL CHECK (finished >= 0),
    total         NUMERIC(14,2) NOT NULL CHECK (total >= 0),
    note          TEXT,
    related_link  VARCHAR(500),
    days_late     SMALLINT NOT NULL DEFAULT 0,
    percentage    SMALLINT NOT NULL DEFAULT 100,                                  -- 100 on time, −20 per day late, 0 from 5 days
    submitted_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    approved_at   TIMESTAMPTZ,
    approved_by   BIGINT REFERENCES users(id) ON DELETE SET NULL,
    deleted_at    TIMESTAMPTZ,
    deleted_by    BIGINT REFERENCES users(id) ON DELETE SET NULL
);
-- One live submission per KPI per month; a deleted one frees the KPI to be submitted again.
CREATE UNIQUE INDEX IF NOT EXISTS kpi_submissions_once ON kpi_submissions (task_id, period_year, period_month) WHERE deleted_at IS NULL AND task_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS kpi_submissions_period ON kpi_submissions (period_year, period_month) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS kpi_submissions_approver ON kpi_submissions (approver_id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS kpi_submissions_user ON kpi_submissions (user_id) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS kpi_submission_files (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL REFERENCES kpi_submissions(id) ON DELETE CASCADE,
    name          VARCHAR(200) NOT NULL,
    path          VARCHAR(200) NOT NULL,                                          -- under storage/kpi/, never public
    mime          VARCHAR(120) NOT NULL,
    size          BIGINT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS kpi_submission_files_sub ON kpi_submission_files (submission_id);

-- Permission. (On a fresh install this runs before the roles exist and skips; the seed adds it.)
INSERT INTO permissions (module, key, label, sort)
SELECT 'core', 'kpi_submissions', 'KPI submissions', 65
WHERE EXISTS (SELECT 1 FROM roles)
ON CONFLICT (key) DO NOTHING;

INSERT INTO role_permissions (role_id, permission_id, can_view, can_create, can_edit, can_delete, can_import, can_export, can_download)
SELECT r.id, p.id, position('v' IN d.l) > 0, position('c' IN d.l) > 0, FALSE, FALSE, FALSE, position('x' IN d.l) > 0, position('w' IN d.l) > 0
FROM (VALUES ('admin','vcxw'),('management','vxw'),('bu_manager','vcxw'),('manager','vcxw'),('member','vcw')) AS d(role, l)
JOIN roles r ON r.slug = d.role
JOIN permissions p ON p.key = 'kpi_submissions'
ON CONFLICT (role_id, permission_id) DO NOTHING;
