-- Daily oil prices from PTT OR (orapiweb.pttor.com, GetOilPrice). Synced a few times every morning; a price is only
-- stored when it differs from the last one of that fuel, so the table holds the price changes, not one row per day.
CREATE TABLE IF NOT EXISTS oil_products (
    code       VARCHAR(40) PRIMARY KEY,                 -- from the English name, e.g. diesel_b20
    name_en    VARCHAR(80) NOT NULL,
    name_th    VARCHAR(120),
    sort       SMALLINT NOT NULL DEFAULT 0,
    active     BOOLEAN NOT NULL DEFAULT TRUE,           -- still in PTT's latest list
    first_seen TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS oil_prices (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code VARCHAR(40) NOT NULL REFERENCES oil_products(code) ON UPDATE CASCADE,
    price        NUMERIC(8,2) NOT NULL,
    effective_at TIMESTAMPTZ NOT NULL,                  -- PRICE_DATE: when PTT started this price
    fetched_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (product_code, effective_at)
);
CREATE INDEX IF NOT EXISTS oil_prices_product_idx ON oil_prices (product_code, effective_at DESC);
CREATE INDEX IF NOT EXISTS oil_prices_effective_idx ON oil_prices (effective_at DESC);

CREATE TABLE IF NOT EXISTS oil_price_syncs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    source      VARCHAR(12) NOT NULL,                   -- schedule | manual | history
    for_date    DATE NOT NULL,                          -- the day asked for
    user_id     BIGINT REFERENCES users(id) ON DELETE SET NULL,
    user_name   VARCHAR(150),
    status      VARCHAR(8) NOT NULL,                    -- ok | failed
    products    SMALLINT NOT NULL DEFAULT 0,
    changed     SMALLINT NOT NULL DEFAULT 0,
    price_date  TIMESTAMPTZ,
    message     VARCHAR(500),
    duration_ms INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS oil_price_syncs_run_idx ON oil_price_syncs (run_at DESC);

