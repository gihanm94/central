-- PDF signing.
-- Management → Member signatures keeps one signature image per person (uploaded or drawn there);
-- User Management → Sign PDF lets a person place their own signature on a PDF. Every signed PDF is kept
-- (original and signed copy, where each signature was placed, file fingerprints) and listed for
-- Management and the Administrator.
CREATE TABLE IF NOT EXISTS user_signatures (
    user_id     BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    file        VARCHAR(120) NOT NULL,                 -- file name in storage/signatures
    source      VARCHAR(10)  NOT NULL DEFAULT 'upload' CHECK (source IN ('upload', 'drawn')),
    updated_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS pdf_signatures (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT REFERENCES users(id) ON DELETE SET NULL,
    user_name       VARCHAR(150) NOT NULL,               -- kept as it was when signing
    department_id   BIGINT REFERENCES departments(id) ON DELETE SET NULL,
    title           VARCHAR(200) NOT NULL,               -- the uploaded file name
    original_file   VARCHAR(160) NOT NULL,               -- in storage/pdf-signs
    signed_file     VARCHAR(160) NOT NULL,
    original_sha256 CHAR(64) NOT NULL,
    signed_sha256   CHAR(64) NOT NULL,
    original_size   INTEGER NOT NULL DEFAULT 0,
    signed_size     INTEGER NOT NULL DEFAULT 0,
    pages           INTEGER NOT NULL DEFAULT 0,
    placements      JSONB NOT NULL DEFAULT '[]',         -- [{page, x, y, w, h}] as fractions of the page
    ip_address      VARCHAR(45),
    user_agent      VARCHAR(250),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS pdf_signatures_user_idx ON pdf_signatures (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS pdf_signatures_created_idx ON pdf_signatures (created_at DESC);

-- Everybody may sign their own PDFs. (On a fresh install this runs before the roles exist and skips; the seed adds it.)
INSERT INTO permissions (module, key, label, sort)
SELECT 'core', 'pdf_sign', 'Sign PDF', 97 WHERE EXISTS (SELECT 1 FROM roles) ON CONFLICT (key) DO NOTHING;
INSERT INTO role_permissions (role_id, permission_id, can_view, can_create, can_edit, can_delete, can_import, can_export, can_download)
SELECT r.id, p.id, TRUE, TRUE, FALSE, FALSE, FALSE, FALSE, TRUE FROM roles r JOIN permissions p ON p.key = 'pdf_sign'
ON CONFLICT (role_id, permission_id) DO NOTHING;
