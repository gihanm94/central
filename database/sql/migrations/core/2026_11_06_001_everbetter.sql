-- Everbetter: improvement projects. People run projects (title, dates, members) and present them to Management on the
-- quarter's presentation day: Project Initiation, Closure or Extend time. Management acknowledges each request and,
-- after the presentation, records the result (initiation approved → project approved; closure → closed; extension → new end date).
CREATE TABLE IF NOT EXISTS everbetter_sessions (               -- one presentation day per quarter, set by Management
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year        SMALLINT NOT NULL CHECK (year BETWEEN 2000 AND 2100),
    quarter     SMALLINT NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    present_on  DATE NOT NULL,
    place       VARCHAR(200),
    note        VARCHAR(500),
    created_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (year, quarter)
);

CREATE TABLE IF NOT EXISTS everbetter_projects (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR(200) NOT NULL,
    description   TEXT,
    start_date    DATE NOT NULL,
    end_date      DATE NOT NULL CHECK (end_date >= start_date),
    owner_id      BIGINT REFERENCES users(id) ON DELETE SET NULL,
    owner_name    VARCHAR(150) NOT NULL,
    department_id BIGINT REFERENCES departments(id) ON DELETE SET NULL,
    status        VARCHAR(10) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'approved', 'rejected', 'closed')),
    approved_at   TIMESTAMPTZ,
    closed_at     TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at    TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS everbetter_projects_owner_idx ON everbetter_projects (owner_id) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS everbetter_members (
    project_id BIGINT NOT NULL REFERENCES everbetter_projects(id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (project_id, user_id)
);
CREATE INDEX IF NOT EXISTS everbetter_members_user_idx ON everbetter_members (user_id);

CREATE TABLE IF NOT EXISTS everbetter_presentations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      BIGINT NOT NULL REFERENCES everbetter_projects(id) ON DELETE CASCADE,
    session_id      BIGINT NOT NULL REFERENCES everbetter_sessions(id),
    kind            VARCHAR(12) NOT NULL CHECK (kind IN ('initiation', 'closure', 'extension')),
    new_end_date    DATE,                                         -- extension: the end date asked for
    note            TEXT,
    requested_by    BIGINT REFERENCES users(id) ON DELETE SET NULL,
    requested_name  VARCHAR(150) NOT NULL,
    requested_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    status          VARCHAR(12) NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted', 'acknowledged', 'withdrawn')),
    acknowledged_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    acknowledged_name VARCHAR(150),
    acknowledged_at TIMESTAMPTZ,
    result          VARCHAR(10) CHECK (result IN ('approved', 'rejected')),
    result_note     TEXT,
    decided_by      BIGINT REFERENCES users(id) ON DELETE SET NULL,
    decided_name    VARCHAR(150),
    decided_at      TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS everbetter_presentations_project_idx ON everbetter_presentations (project_id, requested_at DESC);
CREATE INDEX IF NOT EXISTS everbetter_presentations_session_idx ON everbetter_presentations (session_id);

-- Everybody may run projects. (On a fresh install this runs before the roles exist and skips; the seed adds it.)
INSERT INTO permissions (module, key, label, sort)
SELECT 'core', 'everbetter', 'Everbetter projects', 98 WHERE EXISTS (SELECT 1 FROM roles) ON CONFLICT (key) DO NOTHING;
INSERT INTO role_permissions (role_id, permission_id, can_view, can_create, can_edit, can_delete, can_import, can_export, can_download)
SELECT r.id, p.id, TRUE, TRUE, TRUE, FALSE, FALSE, FALSE, FALSE FROM roles r JOIN permissions p ON p.key = 'everbetter'
ON CONFLICT (role_id, permission_id) DO NOTHING;
