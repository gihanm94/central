-- KPI calculator (User Management → KPI calculator): the yearly appraisal score out of 100.
-- How each KPI & OKR is scored: direction, what the monthly numbers mean, measuring period and weight.
ALTER TABLE kpis ADD COLUMN IF NOT EXISTS direction VARCHAR(5)  NOT NULL DEFAULT 'min';      -- min = not less than, max = not more than
ALTER TABLE kpis ADD COLUMN IF NOT EXISTS measure   VARCHAR(10) NOT NULL DEFAULT 'percent';  -- percent = finished ÷ total × 100, count = finished
ALTER TABLE kpis ADD COLUMN IF NOT EXISTS period    VARCHAR(10) NOT NULL DEFAULT 'month';    -- month | quarter | half | year
ALTER TABLE kpis ADD COLUMN IF NOT EXISTS weight    NUMERIC(6,2);                            -- % of the KPI section
DO $$ BEGIN
    ALTER TABLE kpis ADD CONSTRAINT kpis_scoring_check CHECK (direction IN ('min','max') AND measure IN ('percent','count') AND period IN ('month','quarter','half','year'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- One saved score per person and year (recalculated as often as needed).
CREATE TABLE IF NOT EXISTS kpi_scores (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    year          SMALLINT NOT NULL,
    month         SMALLINT NOT NULL CHECK (month BETWEEN 1 AND 12),        -- calculated up to this month
    emp_group     VARCHAR(10) NOT NULL DEFAULT 'bu',
    inputs        JSONB NOT NULL DEFAULT '{}',                             -- QO, sales, QMS, leader, absence, warnings
    details       JSONB NOT NULL DEFAULT '{}',                             -- every section's figures as calculated
    score         NUMERIC(6,2) NOT NULL DEFAULT 0,
    calculated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    calculated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, year)
);

-- (On a fresh install this runs before the roles exist and skips; the seed adds it.)
INSERT INTO permissions (module, key, label, sort)
SELECT 'core', 'kpi_calculator', 'KPI calculator', 66 WHERE EXISTS (SELECT 1 FROM roles) ON CONFLICT (key) DO NOTHING;
INSERT INTO role_permissions (role_id, permission_id, can_view, can_create, can_edit, can_delete, can_import, can_export, can_download)
SELECT r.id, p.id, position('v' IN d.l) > 0, position('e' IN d.l) > 0, position('e' IN d.l) > 0, FALSE, FALSE, position('x' IN d.l) > 0, position('x' IN d.l) > 0
FROM (VALUES ('admin','vex'),('management','vx'),('bu_manager','vex'),('manager',''),('member','')) AS d(role, l)
JOIN roles r ON r.slug = d.role JOIN permissions p ON p.key = 'kpi_calculator'
ON CONFLICT (role_id, permission_id) DO NOTHING;
