-- e-Tax (INET) documents: one row per invoice / credit note, with the state of each document type
-- 388 = tax invoice, T01 = receipt / tax invoice, 81 = credit note.
CREATE TABLE IF NOT EXISTS inets (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    no_invoice         BIGINT NOT NULL,                       -- the ERP invoice number
    custom_invoice_no  TEXT,
    invoice_date       TIMESTAMPTZ,
    is_credit          BOOLEAN NOT NULL DEFAULT FALSE,
    is_manual          BOOLEAN NOT NULL DEFAULT FALSE,        -- "auto pdf" was NOT chosen when generating
    is_international   BOOLEAN NOT NULL DEFAULT FALSE,
    is_issue           BOOLEAN NOT NULL DEFAULT FALSE,
    is_correction      BOOLEAN NOT NULL DEFAULT FALSE,
    order_id           BIGINT,
    customer_order_number TEXT,
    delivery_note_number  BIGINT,
    seller_name        TEXT,
    department_name    TEXT,
    customer_id        BIGINT,
    customer_code      TEXT,
    customer_name      TEXT,
    currency_code      TEXT,
    tax_type           TEXT,
    tax_id             TEXT,
    branch             TEXT,
    email              TEXT,
    amount             NUMERIC(24,6) NOT NULL DEFAULT 0,
    tax_amount         NUMERIC(24,6) NOT NULL DEFAULT 0,
    total_amount       NUMERIC(24,6) NOT NULL DEFAULT 0,
    exchange_rate      NUMERIC(24,8),
    tax_rate           NUMERIC(10,4),
    product_count      INTEGER NOT NULL DEFAULT 0,
    remark             TEXT,
    is_388_generate BOOLEAN NOT NULL DEFAULT FALSE, is_t01_generate BOOLEAN NOT NULL DEFAULT FALSE, is_81_generate BOOLEAN NOT NULL DEFAULT FALSE,
    is_388_send     BOOLEAN NOT NULL DEFAULT FALSE, is_t01_send     BOOLEAN NOT NULL DEFAULT FALSE, is_81_send     BOOLEAN NOT NULL DEFAULT FALSE,
    is_388_fetch    BOOLEAN NOT NULL DEFAULT FALSE, is_t01_fetch    BOOLEAN NOT NULL DEFAULT FALSE, is_81_fetch    BOOLEAN NOT NULL DEFAULT FALSE,
    is_388_download BOOLEAN NOT NULL DEFAULT FALSE, is_t01_download BOOLEAN NOT NULL DEFAULT FALSE, is_81_download BOOLEAN NOT NULL DEFAULT FALSE,
    pdf_388 TEXT, pdf_t01 TEXT, pdf_81 TEXT,
    inet_pdf_388 TEXT, inet_pdf_t01 TEXT, inet_pdf_81 TEXT,
    transaction_388 TEXT, transaction_t01 TEXT, transaction_81 TEXT,
    text_388 TEXT, text_t01 TEXT, text_81 TEXT,
    created_by BIGINT, updated_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (no_invoice, is_credit)
);
CREATE INDEX IF NOT EXISTS inets_customer_idx ON inets (customer_code);
